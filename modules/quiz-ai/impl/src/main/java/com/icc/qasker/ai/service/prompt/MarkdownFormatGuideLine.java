package com.icc.qasker.ai.service.prompt;

import lombok.AccessLevel;
import lombok.NoArgsConstructor;

/**
 * 전 퀴즈 타입 공통 출력 서식 규약. 생성 본문(지문·선지·해설)이 렌더러(GFM + remark-math + KaTeX)에서 의도대로 표시되도록 마크다운 형태를 강제한다.
 * {@code QuizType}이 타입별 GuideLine 앞에 이 규약을 prepend한다(계약 §7.3-1, 단일 주입점).
 *
 * <p>결정론적 정규화기가 사후에 "글루된 표"만 복원하므로, 이 규약은 그 앞단에서 애초에 올바른 서식이 생성되게 하는 1차 보장이다(특히 구분행 소실·이스케이프처럼 정규화로
 * 복원 불가한 실패 모드).
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
public class MarkdownFormatGuideLine {

  public static final String content =
      """
    # 출력 서식 규약 (전 문항 공통 — 반드시 준수)
    문제 본문·선택지·해설은 GitHub Flavored Markdown으로 작성한다. 아래 형태 규약을 지켜야 렌더러에서 표는 표답게, 인용은 인용답게 표시된다.

    - **표**: 헤더행 / 구분행(`| --- | --- |`) / 각 본문행을 **반드시 각각 새 줄**로 작성한다. 한 줄에 파이프를 몰아넣지 않는다. 표 앞뒤에는 빈 줄을 둔다. (예:
      `| 항목 | 값 |`↵`| --- | --- |`↵`| 가 | 1 |`)
    - **블록 요소**(표·인용문 `>`·코드 펜스 ```` ``` ````·목록)는 앞뒤에 빈 줄을 둔다.
    - **줄바꿈**: 문단 분리는 빈 줄(연속 두 번의 개행)로 한다. 단일 개행 하나만으로는 줄바꿈이 되지 않으므로, 줄바꿈이 필요하면 문단을 나누거나 줄 끝에 공백 2칸을 둔다.
    - **수식**: 인라인은 `$...$`, 블록은 `$$...$$`로 감싼다. **블록 수식의 `$$` 구분자는 각각 독립된 줄에 둔다**(한 줄로 쓴 `$$...$$`는 가운데 정렬 블록이 아니라 인라인으로 렌더된다). 수식·논리식의 세로 막대는 맨 `|`가 아니라 `$...$` 안에서 `\\mid`로 쓴다(예: `$P(A \\mid B)$`).
    - **리터럴 이스케이프**:
      - 통화·금액 등 수식이 아닌 리터럴 `$`는 `\\$`로 이스케이프한다(한 줄에 `$`가 2개면 그 사이가 수식으로 잘못 해석된다).
      - 표 셀 안에서 내용으로 쓰는 리터럴 `|`는 `\\|`로 이스케이프한다.
    - 원시 HTML 태그는 사용하지 않는다.

    """;
}
